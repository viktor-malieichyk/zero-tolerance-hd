#!/usr/bin/env python3
"""Generate zt_hud_font.h: the HUD's ammo count glyphs ("0123456789%") in Menlo Bold at several pixel
sizes, antialiased (4-bit coverage, two pixels per byte, high nibble left). The renderer draws a count at
the largest size not above the one it wants.

    python3 make_hud_font.py [Menlo.ttc] > zt_hud_font.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Menlo.ttc"
CHARS = "0123456789%"
SIZES = [10, 12, 14, 16, 18, 20, 24, 28, 32, 40, 48, 60]

print("/* HUD ammo count glyphs \"0123456789%\", generated by make_hud_font.py from Menlo Bold */")
print("/* per size: pixel size, glyph cell width and height, offset of the first glyph in zt_hud_font_data;")
print("   glyphs are cells of w x h 4-bit coverage values, two per byte (high nibble left), rows padded to a byte */")
data, sizes = [], []
for s in SIZES:
    font = ImageFont.truetype(path, s, index=1)
    # one cell for all glyphs: Menlo is monospaced; height from the digits' ink (no ascender/descender room)
    boxes = [font.getbbox(c) for c in CHARS]
    top = min(b[1] for b in boxes); bottom = max(b[3] for b in boxes)
    w = max(int(font.getlength(c)) for c in CHARS); h = bottom - top
    sizes.append((s, w, h, len(data)))
    for c in CHARS:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, -top), c, font=font, fill=255)
        for y in range(h):
            row = [(im.getpixel((x, y)) + 8) // 17 for x in range(w)]
            if len(row) % 2: row.append(0)
            data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
print(f"#define ZT_HUD_FONT_SIZES {len(SIZES)}")
print("static const struct { unsigned char px, w, h; unsigned int off; } zt_hud_font_size[ZT_HUD_FONT_SIZES] = {")
print(",\n".join(f"  {{{s}, {w}, {h}, {o}}}" for s, w, h, o in sizes))
print("};")
print(f"static const unsigned char zt_hud_font_data[{len(data)}] = {{")
for i in range(0, len(data), 24):
    print("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
print("};")
