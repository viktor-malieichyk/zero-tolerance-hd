#!/usr/bin/env python3
"""Write zt_steam_ips.h for ew_wrap.c: the ROM patches built into the Steam DLL, each with the checks it is
applied under (original size and CRC32; patched size and CRC32).

    python3 gen_ips_header.py <out.h> <name> <original ROM> <IPS> [<name> <original ROM> <IPS> ...]

The first is the game the Steam frontend loads (its res/game); the others are games the DLL switches to
when their ROMs are found in the game folder (found by size and CRC32, whatever the file is called).
make_patch.py builds the IPS files.
"""
import sys, zlib

def apply(rom, ips):
    assert ips[:5] == b"PATCH" and ips[-3:] == b"EOF", "not an IPS file"
    r = bytearray(rom); k = 5
    while ips[k:k + 3] != b"EOF":
        off = int.from_bytes(ips[k:k + 3], "big"); n = int.from_bytes(ips[k + 3:k + 5], "big"); k += 5
        if n:
            data = ips[k:k + n]; k += n
        else:
            data = bytes([ips[k + 2]]) * int.from_bytes(ips[k:k + 2], "big"); k += 3
        if off + len(data) > len(r): r += b"\xFF" * (off + len(data) - len(r))   # a grown ROM (FF-filled)
        r[off:off + len(data)] = data
    return bytes(r)

out, args = sys.argv[1], sys.argv[2:]
assert args and len(args) % 3 == 0, __doc__
with open(out, "w") as f:
    f.write("/* generated by gen_ips_header.py: the zt_high_fps patches built into the Steam DLL */\n")
    f.write("typedef struct { const char *name; unsigned size, crc, patched_size, patched_crc; "
            "const unsigned char *ips; unsigned ips_size; } zt_rom_patch_t;\n")
    entries = []
    for i in range(0, len(args), 3):
        name, rom, ips = args[i], open(args[i + 1], "rb").read(), open(args[i + 2], "rb").read()
        new = apply(rom, ips)
        f.write("static const unsigned char zt_ips_%d[%d] = {\n" % (i // 3, len(ips)))
        for j in range(0, len(ips), 16):
            f.write("  " + ", ".join("0x%02X" % b for b in ips[j:j + 16]) + ",\n")
        f.write("};\n")
        entries.append('  {"%s", %du, 0x%08Xu, %du, 0x%08Xu, zt_ips_%d, %d},\n'
                       % (name, len(rom), zlib.crc32(rom) & 0xFFFFFFFF, len(new), zlib.crc32(new) & 0xFFFFFFFF,
                          i // 3, len(ips)))
        print("%s: %d byte patch" % (name, len(ips)))
    f.write("static const zt_rom_patch_t zt_rom_patches[] = {\n" + "".join(entries) + "};\n")
    f.write("#define ZT_NPATCHES %d\n" % len(entries))
print("wrote", out)
