#!/usr/bin/env python3
"""Write zt_steam_ips.h for ew_wrap.c: the Steam ROM patch and the CRC32s it is checked against.

    python3 gen_ips_header.py <Steam game folder> <zt_high_fps_steam.ips> <out.h>

The original ROM is read from <Steam game folder>/res/game; make_patch.py --steam builds the IPS.
"""
import sys, zlib
rom = open(sys.argv[1] + "/res/game", "rb").read()
ips = open(sys.argv[2], "rb").read()
assert ips[:5] == b"PATCH" and ips[-3:] == b"EOF", "not an IPS file"
r = bytearray(rom); k = 5
while ips[k:k + 3] != b"EOF":
    off = int.from_bytes(ips[k:k + 3], "big"); n = int.from_bytes(ips[k + 3:k + 5], "big"); k += 5
    if n: r[off:off + n] = ips[k:k + n]; k += n
    else: c = int.from_bytes(ips[k:k + 2], "big"); r[off:off + c] = bytes([ips[k + 2]]) * c; k += 3
with open(sys.argv[3], "w") as f:
    f.write("/* generated by gen_ips_header.py: zt_high_fps patch for the Steam release's res/game */\n")
    f.write("#define ZT_ROM_SIZE %d\n#define ZT_ROM_CRC 0x%08Xu\n#define ZT_PATCHED_CRC 0x%08Xu\n"
            % (len(rom), zlib.crc32(rom) & 0xFFFFFFFF, zlib.crc32(bytes(r)) & 0xFFFFFFFF))
    f.write("static const unsigned char zt_steam_ips[%d] = {\n" % len(ips))
    for i in range(0, len(ips), 16):
        f.write("  " + ", ".join("0x%02X" % b for b in ips[i:i + 16]) + ",\n")
    f.write("};\n")
print("wrote", sys.argv[3], "(%d byte patch)" % len(ips))
